package web

import "fmt"

// Catálogo de mensagens do painel. Hoje só pt-BR; outro idioma é outro mapa
// com as mesmas chaves (e a escolha pelo Accept-Language ou pela conta).
// Mensagens com %d/%s recebem os argumentos de msg.
//
// As mensagens de erro das ações (unidade em uso, e-mail já cadastrado…)
// vêm do pacote api, as mesmas das rotas /v1.
var catalog = ptBR

func msg(key string, args ...any) string {
	m, ok := catalog[key]
	if !ok {
		return key
	}
	if len(args) > 0 {
		return fmt.Sprintf(m, args...)
	}
	return m
}

// label é a tradução de prefixo+valor, ou o próprio valor se não há.
func label(prefix, value string) string {
	if m, ok := catalog[prefix+value]; ok {
		return m
	}
	return value
}

